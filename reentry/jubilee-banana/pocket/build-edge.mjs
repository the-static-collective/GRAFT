// Reproducibly package original checked-in JavaScript for Supabase Edge static
// serving. No API keys, backend, runtime databases, data collection, or bundler.
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
const here=dirname(fileURLToPath(import.meta.url));
const read=path=>readFileSync(join(here,path),'utf8');
const html=read('index.html').replace('src="./app.mjs"','src="?asset=app"');
const app=read('app.mjs')
 .replace("'../gram/portable-gram.mjs'","'?asset=gram'")
 .replace("'../bridge/gram-reentry.mjs'","'?asset=reentry'")
 .replace("'../forest/forest-projection.mjs'","'?asset=forest'");
const gram=read('../gram/portable-gram.mjs');
const forest=read('../forest/forest-projection.mjs');
const bridge=read('../bridge/participation-bridge.mjs');
const reentry=read('../bridge/gram-reentry.mjs')
 .replace("'../gram/portable-gram.mjs'","'?asset=gram'")
 .replace("'./participation-bridge.mjs'","'?asset=participation'");
function requireIncludes(name,value,pattern){if(!value.includes(pattern))throw Error(name+': missing '+pattern);}
requireIncludes('html',html,'src="?asset=app"');
requireIncludes('app',app,"'?asset=reentry'");
requireIncludes('app',app,"'?asset=forest'");
requireIncludes('reentry',reentry,"'?asset=participation'");
if([app,reentry].some(s=>/from ['"]\.\.\//.test(s)))throw Error('Unrewritten import remains');
const out=['// GENERATED by pocket/build-edge.mjs; no secrets or authority.',
 ...Object.entries({HTML:html,APP:app,GRAM:gram,PARTICIPATION:bridge,REENTRY:reentry,FOREST:forest})
   .map(([k,v])=>'export const '+k+' = '+JSON.stringify(v)+';')].join('\n');
const target=join(here,'edge','assets.ts');mkdirSync(dirname(target),{recursive:true});
writeFileSync(target,out+'\n');
console.log('Generated Edge assets:',target,'bytes:',out.length);
